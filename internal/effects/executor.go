package effects

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	"sdlc-coordinator/internal/adapters/im"
	"sdlc-coordinator/internal/model"
	"sdlc-coordinator/internal/orchestrator"
)

const KindSendIMMessage = "send_im_message"

type Executor struct {
	im im.Backend
}

func NewExecutor(imBackend im.Backend) *Executor {
	return &Executor{im: imBackend}
}

func (e *Executor) ExecuteEffect(ctx context.Context, effect *model.Effect) (string, error) {
	if effect == nil {
		return "", errors.New("effect is required")
	}

	switch strings.TrimSpace(effect.Kind) {
	case KindSendIMMessage:
		return e.executeSendIMMessage(ctx, effect)
	default:
		return "", fmt.Errorf("unsupported effect kind %q", effect.Kind)
	}
}

type sendIMMessageRequest struct {
	Body     string          `json:"body,omitempty"`
	Mentions []string        `json:"mentions,omitempty"`
	Payload  json.RawMessage `json:"payload,omitempty"`
}

func (e *Executor) executeSendIMMessage(ctx context.Context, effect *model.Effect) (string, error) {
	if e.im == nil {
		// 未配置 IM provider 时通知是显式禁用的:安全跳过,不进入失败重试。
		return `{"skipped":"im disabled"}`, nil
	}

	var req sendIMMessageRequest
	if strings.TrimSpace(effect.RequestJSON) != "" {
		if err := json.Unmarshal([]byte(effect.RequestJSON), &req); err != nil {
			return "", fmt.Errorf("decode send_im_message request: %w", err)
		}
	}
	if len(req.Payload) > 0 && string(req.Payload) != "null" {
		return "", errors.New("raw payload is not supported; message body is generated by coordinator")
	}
	if strings.TrimSpace(req.Body) == "" {
		return "", errors.New("body is required")
	}

	// orchestrator 侧以字面量 "default" 标记默认目的地;backend 契约是空串回落
	// 默认配置。不翻译则 "default" 被当真实 chat_id 发出(Telegram 400 chat not found)。
	target := strings.TrimSpace(effect.Target)
	if target == "default" {
		target = ""
	}
	message, err := e.im.SendMessage(ctx, im.SendMessageRequest{
		Target:   target,
		Body:     req.Body,
		Mentions: req.Mentions,
	})
	if err != nil {
		// 投递未核验(im 层结构化错误)转译为编排层哨兵:记账层按哨兵记
		// 独立终态,不感知 im 细节;其余错误原样透传。
		var unverified *im.DeliveryUnverifiedError
		if errors.As(err, &unverified) {
			return "", fmt.Errorf("%w: %s", orchestrator.ErrEffectDeliveryUnverified, err.Error())
		}
		return "", err
	}

	if message == nil {
		message = &im.Message{}
	}
	raw, err := json.Marshal(map[string]any{
		"message_id": message.ID,
		"provider":   message.Provider,
		"raw":        json.RawMessage(nonEmptyJSON(message.RawJSON)),
	})
	if err != nil {
		return "", fmt.Errorf("marshal effect execution response: %w", err)
	}
	return string(raw), nil
}

func nonEmptyJSON(raw string) string {
	if strings.TrimSpace(raw) == "" {
		return "{}"
	}
	return raw
}
